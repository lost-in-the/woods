# frozen_string_literal: true

require_relative 'container_attribution'

module Woods
  # The size of an application unit's own source file (#810): `lines` (every
  # line) and `loc` (lines with anything but whitespace), published as
  # `metadata[:source_size]` and as `lines` and `loc` on the unit's graph node.
  #
  # The count is of the file, not of the unit: two units read from one file
  # carry the same numbers, and inlined concerns are not added. A reader that
  # totals a package, a namespace or a cluster counts each distinct
  # `file_path` once; {GraphAnalyzer#package_sizes} does that for packages.
  #
  # Only application code is counted ({ContainerAttribution::APPLICATION_TYPES}
  # without routes, which all point at the routes file), and only a regular
  # file under the application root: framework and gem sources, engines,
  # configuration, migrations and tests carry no size, so absence never
  # reads as zero. Neither does a generated class (an `async_method` worker),
  # whose file is the declaring unit's. The count is a pure function of the
  # file's bytes, so a full and an incremental run publish the same numbers.
  module SourceSize
    # Unit types that carry a size.
    TYPES = (ContainerAttribution::APPLICATION_TYPES - %i[route]).freeze

    module_function

    # Set or clear `metadata[:source_size]`.
    #
    # @param unit [ExtractedUnit]
    # @param root [String, Pathname] the application root
    # @return [void]
    def record(unit, root:)
      return unless unit.metadata.is_a?(Hash)

      size = for_unit(unit, root: root)
      if size
        unit.metadata[:source_size] = size
      else
        unit.metadata.delete(:source_size)
      end
    end

    # @param unit [ExtractedUnit]
    # @param root [String, Pathname]
    # @return [Hash{Symbol => Integer}, nil] `{ lines:, loc: }`, or nil when
    #   the unit is not application code, is generated by another unit's
    #   declaration, or its file is not under +root+
    def for_unit(unit, root:)
      return nil unless TYPES.include?(unit.type.to_sym)
      return nil if generated?(unit)

      path = inside(unit.file_path, root)
      path && count(File.binread(path))
    rescue SystemCallError, IOError
      nil
    end

    # @param source [String] a file's bytes
    # @return [Hash{Symbol => Integer}] `{ lines:, loc: }`
    def count(source)
      lines = source.b.lines
      { lines: lines.size, loc: lines.count { |line| line.match?(/[^ \t\r\n\f\v]/n) } }
    end

    # A class another unit's declaration generates (an `async_method` worker)
    # has no file of its own: its `file_path` is the declaring unit's file,
    # whose size is the declaring unit's.
    def generated?(unit)
      metadata = unit.metadata.is_a?(Hash) ? unit.metadata : {}
      metadata[:generated] == true || metadata['generated'] == true
    end

    # @return [String, nil] the absolute path when it names a regular file under +root+
    def inside(file_path, root)
      return nil unless file_path.is_a?(String) && !file_path.empty?

      base = File.expand_path(root.to_s)
      path = File.expand_path(file_path, base)
      return nil unless path.start_with?("#{base}/") && File.file?(path)

      path
    end
  end
end
